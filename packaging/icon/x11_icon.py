#!/usr/bin/env python3
"""The icon's PNGs → the X11 window icon for the standalones (render.sh runs it; the result is committed):

    x11_icon.py <out.inc> <png> ...

writes the `_NET_WM_ICON` property's value as a C++ array: for each PNG its width, its height, then its pixels
row by row as 0xAARRGGBB, one `unsigned long` each (X11's format 32). plugin/src/ui/PianoUI.cpp includes it for
DPF's DGL_X11_WINDOW_ICON_NAME; DGL_X11_WINDOW_ICON_SIZE (plugin/CMakeLists.txt) is its length."""
import sys

from PIL import Image

out, pngs = sys.argv[1], sys.argv[2:]
values = []
for path in pngs:
    im = Image.open(path).convert("RGBA")
    values += [im.width, im.height]
    px = im.tobytes()  # RGBA, row by row
    values += [(px[i + 3] << 24) | (px[i] << 16) | (px[i + 1] << 8) | px[i + 2] for i in range(0, len(px), 4)]
sizes = ", ".join(f"{Image.open(p).width} px" for p in pngs)
lines = [", ".join(f"0x{v:08x}" for v in values[i:i + 12]) for i in range(0, len(values), 12)]
with open(out, "w") as f:
    f.write(f"// Generated by packaging/icon/render.sh (x11_icon.py) from dussek.svg: the window's icon on X11 ({sizes}),\n"
            f"// _NET_WM_ICON's value: width, height, then ARGB pixels. {len(values)} values: DGL_X11_WINDOW_ICON_SIZE.\n")
    f.write("static const unsigned long kPeWindowIcon[] = {\n    " + ",\n    ".join(lines) + "\n};\n")
print(f"{out}: {len(values)} values")
